import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileTree, localFile, sha256, verifyInventory } from './node-files.mjs';

export const backendProtocol = 1;
export const bindgenVersion = '0.2.128';
export const wasmTarget = 'wasm32-unknown-unknown';
export const backendHash = (value) =>
  createHash('sha256').update(JSON.stringify(value)).digest('hex');
export const rustSupplySchema = 'nelyx.rust-supply/v1';
export const backendFiles = [
  'backend.js',
  'backend_bg.wasm',
  'backend.d.ts',
  'backend_bg.wasm.d.ts',
];
export const backendPackages = { web: 'backend-wasm', tauri: 'backend-tauri' };
export const backendCrates = {
  'backend-rust': 'nelyx-backend-core',
  'backend-wasm': 'nelyx-backend-wasm',
  'backend-tauri': 'tauri-plugin-nelyx-backend',
};

const generated = new Set([
  'target',
  '.git',
  '.nelyx',
  'node_modules',
  '.gradle',
  '.kotlin',
  '.tauri',
]);

export function rustInputFiles(root) {
  const files = [];
  function visit(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const generatedAndroid =
        entry.name === 'build' && path.relative(root, directory) === 'android';
      if (
        generated.has(entry.name) ||
        generatedAndroid ||
        (directory === root && entry.name === 'locks') ||
        (['autogenerated', 'schemas'].includes(entry.name) &&
          path.basename(directory) === 'permissions')
      )
        continue;
      const file = path.join(directory, entry.name);
      if (entry.isDirectory()) visit(file);
      else if (entry.isFile()) files.push(file);
      else throw new Error('Rust inputs require ordinary files: ' + file);
    }
  }
  visit(root);
  return files.sort();
}

export function backendInventory(directory) {
  return fileTree(directory).map((name) => {
    const file = localFile(directory, name);
    return { path: name, bytes: fs.statSync(file).size, sha256: sha256(file) };
  });
}

export function verifyBackendSupply(root, name, version) {
  const packageFile = JSON.parse(fs.readFileSync(localFile(root, 'package.json'), 'utf8'));
  const directory = localFile(root, 'dist');
  const data = JSON.parse(fs.readFileSync(localFile(directory, 'supply.json'), 'utf8'));
  const crate = backendCrates[name];
  if (
    !crate ||
    packageFile.name !== '@nelyx/' + name ||
    data.package !== packageFile.name ||
    data.schema !== rustSupplySchema ||
    data.protocolVersion !== backendProtocol ||
    packageFile.version !== version ||
    data.version !== version ||
    !data.files?.some(({ path }) => path === 'crates/' + crate + '/Cargo.toml') ||
    !data.files?.some(({ path }) => path === 'LICENSE.md')
  )
    throw new Error('Incompatible Rust SDK supply: ' + name);
  verifyInventory(directory, data.files, ['supply.json']);
  if (
    name === 'backend-wasm' &&
    (data.bindgenVersion !== bindgenVersion ||
      data.defaultBackend?.kind !== 'wasm' ||
      data.defaultBackend?.protocolVersion !== backendProtocol ||
      !/^[a-f0-9]{64}$/.test(data.defaultBackend?.sourceId) ||
      !backendFiles.every((name) => data.files.some(({ path }) => path === 'default/' + name)))
  )
    throw new Error('Invalid default backend Wasm supply');
  return { directory, data, id: backendHash(data) };
}
