const plane = 0x01600000000;
export function windowsPhysicalKeyId(scanCode: number): number {
  return windowsToPhysicalMap_.get(scanCode) ?? plane + (scanCode & 0xff);
}
export function windowsLogicalKeyId(keyCode: number, scanCode: number): number {
  if (keyCode === 0xe5) return keyCode;
  const known = scanCodeToLogicalMap_.get(scanCode) ?? windowsToLogicalMap_.get(keyCode);
  if (known !== undefined) return known;
  if (keyCode >= 0x20 && keyCode <= 0xff) {
    if (
      (keyCode >= 0x41 && keyCode <= 0x5a) ||
      (keyCode >= 0xc0 && keyCode <= 0xde && keyCode !== 0xf7)
    )
      return keyCode + 0x20;
    return keyCode;
  }
  return plane + (keyCode >>> 0);
}
