import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
const root = path.resolve(import.meta.dirname, '../..'),
  args = process.argv.slice(2),
  dartArg = args.indexOf('--dart'),
  dart =
    dartArg < 0
      ? path.join(root, '.tmp/work6/dart-dev/dart-sdk/bin/dart.exe')
      : path.resolve(args[dartArg + 1]),
  sdk = path.resolve(dart, '../..'),
  sha = (value) => createHash('sha256').update(value).digest('hex'),
  script = 'tools/Nelyx.FrameworkToTypeScript/dart/bin/word_boundary_properties.dart',
  pinFile = path.join(root, 'Nelyx/upstream/word-boundary-properties.json'),
  target = path.join(root, 'Nelyx/src/foundation/word-boundary-data.ts');
assert.equal(fs.readFileSync(path.join(sdk, 'version'), 'utf8').trim(), '3.14.0-296.0.dev');
assert.equal(
  fs.readFileSync(path.join(sdk, 'revision'), 'utf8').trim(),
  '26d3f09d711197c8dba4ee6fb90604bcbd52e564',
);
const result = spawnSync(dart, [path.join(root, script)], {
  encoding: 'utf8',
  timeout: 1200000,
  windowsHide: true,
  maxBuffer: 1024 * 1024,
});
assert.equal(result.status, 0, result.error?.message ?? result.stderr);
const data = JSON.parse(result.stdout);
assert.equal(data.codePoints, 0x110000);
const output = `// SPDX-License-Identifier: BSD-3-Clause AND Unicode-3.0
// Pinned Dart SDK RegExp property data, generated by generate-word-boundary-data.mjs.
// Full notices: licenses/Dart-LICENSE.md and licenses/characters-UNICODE_LICENSE.txt.
// Source/runtime/output pins: upstream/word-boundary-properties.json.
const ranges:readonly (readonly [number,number])[]=[
${data.ranges.map(([start, end]) => '  [' + start + ',' + end + ']').join(',\n')}
];
export function isWordSpaceOrPunctuation(codePoint:number):boolean{
  if(!Number.isInteger(codePoint)||codePoint<0||codePoint>0x10ffff)throw new RangeError('Invalid Unicode code point');
  let low=0,high=ranges.length;
  while(low<high){const middle=(low+high)>>>1,range=ranges[middle]!;if(codePoint<range[0])high=middle;else if(codePoint>range[1])low=middle+1;else return true;}
  return false;
}
`;
if (args.includes('--initialize')) {
  assert(!fs.existsSync(pinFile), 'Property pin already exists');
  fs.writeFileSync(
    pinFile,
    JSON.stringify(
      {
        schema: 'nelyx.word-boundary-properties/v1',
        flutterRevision: '71e4717a61786faab4c7aa39825989305ed29e8a',
        dartVersion: '3.14.0-296.0.dev',
        dartRevision: '26d3f09d711197c8dba4ee6fb90604bcbd52e564',
        runtime: data.runtime,
        windowsExecutableSha256: sha(fs.readFileSync(dart)),
        predicate: '[\\p{Space_Separator}\\p{Punctuation}]',
        codePoints: data.codePoints,
        matches: data.matches,
        ranges: data.ranges.length,
        script,
        scriptSha256: sha(fs.readFileSync(path.join(root, script))),
        generatedFile: 'Nelyx/src/foundation/word-boundary-data.ts',
        generatedSha256: sha(output),
        scope:
          'One exhaustive pinned-runtime property classification. Product word-boundary predicate uses this fixed table and does not require Dart or host ICU/RegExp. Full RegExp/Unicode library APIs are not claimed.',
      },
      null,
      2,
    ) + '\n',
  );
}
const pin = JSON.parse(fs.readFileSync(pinFile, 'utf8'));
assert.equal(pin.scriptSha256, sha(fs.readFileSync(path.join(root, script))));
assert.equal(pin.generatedSha256, sha(output));
if (process.platform === 'win32')
  assert.equal(pin.windowsExecutableSha256, sha(fs.readFileSync(dart)));
if (args.includes('--check')) assert.equal(fs.readFileSync(target, 'utf8'), output);
else fs.writeFileSync(target, output);
console.log(
  JSON.stringify({
    status: 'PASS',
    mode: args.includes('--check') ? 'check' : 'generate',
    codePoints: data.codePoints,
    matches: data.matches,
    ranges: data.ranges.length,
    sha256: sha(output),
  }),
);
